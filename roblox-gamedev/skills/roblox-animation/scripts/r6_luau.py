"""R6 (and R15) clips -> ONE edit-mode Luau builder of KeyframeSequences. No asset ids, no yields.

  python r6_luau.py --folder ReplicatedStorage.MyAnims --r6 out/Idle/resolved.json ... \
        [--r15 spec.json ...] [--r15-sub R15] [--r6-sub R6] > build.lua

WHY (2026-10-17): a custom-mesh R6 rig with no .blend cannot go through
to_roblox.py (which only knows the community R15 rig's FK bones). r6_clip.py writes `resolved.json`
- the exact Pose CFrames it rendered - and this emits them VERBATIM as CFrame.new(x,y,z, r00..r22),
so there is no Euler decomposition between what was judged and what plays. R15 specs are converted
with to_roblox.convert() so both rigs land in one script under one replaced-wholesale folder.

Behaviour of the emitted script:
  * the target folder is DESTROYED and rebuilt (it is a place-side generated folder; nothing else
    belongs in it), with one subfolder per rig;
  * a joint a clip never keys gets NO Pose; its ancestors that hold keyed joints are Weight-0
    containers - an upper-body clip must not pin the legs (see SKILL.md "An authored clip breaks the
    ones you did not author");
  * markers become KeyframeMarkers on the keyframe at their time (asserted here);
  * returns a one-line-per-clip summary read back from the built instances.
"""
import argparse, json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import r6_joint as RJ  # noqa: E402

R6_TREE = [("Torso", "HumanoidRootPart"), ("Head", "Torso"), ("Right Arm", "Torso"), ("Left Arm", "Torso"),
           ("Right Leg", "Torso"), ("Left Leg", "Torso")]
R6_JOINT_TO_PART = {"RootJoint": "Torso", "Neck": "Head", "Right Shoulder": "Right Arm",
                    "Left Shoulder": "Left Arm", "Right Hip": "Right Leg", "Left Hip": "Left Leg"}


def n(v):
    s = ("%.5f" % v).rstrip("0").rstrip(".")
    return "0" if s in ("", "-0") else s


def r6_clip_lua(res):
    times = [k["t"] for k in res["keys"]]
    rows = []
    mk_at = {}
    for name, t in res.get("markers", []):
        hit = [i for i, kt in enumerate(times) if abs(kt - t) < 1e-4]
        if not hit:
            raise SystemExit(f"{res['name']}: marker {name}@{t} is not on a keyframe")
        mk_at.setdefault(hit[0], []).append(name)
    for i, k in enumerate(res["keys"]):
        style, direction = RJ.ROBLOX_EASE[k["ease"]]
        ps = []
        for jn, pc in sorted(k["poses"].items()):
            part = R6_JOINT_TO_PART[jn]
            vals = list(pc["pos"]) + [x for r in pc["rows"] for x in r]
            ps.append('["%s"]={c={%s}}' % (part, ",".join(n(v) for v in vals)))
        m = ',m={%s}' % ",".join('"%s"' % x for x in mk_at[i]) if i in mk_at else ""
        rows.append('{t=%s,s="%s",d="%s",poses={%s}%s}' % (n(k["t"]), style, direction, ",".join(ps), m))
    return res["name"], res["priority"], res["loop"], "{" + ",".join(rows) + "}"


def r15_clip_lua(path):
    import to_roblox
    d = to_roblox.convert(path)
    rows = []
    for k in d["keyframes"]:
        ps = []
        for j, v in sorted(k["poses"].items()):
            bits = []
            if "r" in v:
                bits.append("r={%s}" % ",".join(n(x) for x in v["r"]))
            if "p" in v:
                bits.append("p={%s}" % ",".join(n(x) for x in v["p"]))
            ps.append('["%s"]={%s}' % (j, ",".join(bits)))
        ms = [m for m, t in d["markers"].items() if abs(t - k["t"]) < 1e-6]
        mk = ",m={%s}" % ",".join('"%s"' % m for m in sorted(ms)) if ms else ""
        rows.append('{t=%s,s="%s",d="%s",poses={%s}%s}' % (n(k["t"]), k["s"], k["d"], ",".join(ps), mk))
    return d["name"], d["priority"], d["loop"], "{" + ",".join(rows) + "}"


HEAD = '''-- GENERATED by roblox-animation/scripts/r6_luau.py - do not hand-edit; regenerate.
-- Rebuilds %(folder)s wholesale: one KeyframeSequence per clip, per rig subfolder.
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local TREES = {
\tR15 = %(r15tree)s,
\tR6 = %(r6tree)s,
}
local function poseCFrame(d)
\tif d.c then
\t\tlocal c = d.c
\t\treturn CFrame.new(c[1], c[2], c[3], c[4], c[5], c[6], c[7], c[8], c[9], c[10], c[11], c[12])
\tend
\tlocal cf = CFrame.new()
\tif d.r then
\t\tcf = CFrame.Angles(0, 0, math.rad(d.r[3])) * CFrame.Angles(0, math.rad(d.r[2]), 0) * CFrame.Angles(math.rad(d.r[1]), 0, 0)
\tend
\tif d.p then
\t\tcf = CFrame.new(d.p[1], d.p[2], d.p[3]) * cf
\tend
\treturn cf
end
local function build(tree, name, priority, loopAnim, KFS)
\tlocal parentOf = {}
\tfor _, pair in ipairs(tree) do parentOf[pair[1]] = pair[2] end
\tlocal seq = Instance.new("KeyframeSequence")
\tseq.Name, seq.Priority, seq.Loop = name, Enum.AnimationPriority[priority], loopAnim
\tfor _, k in ipairs(KFS) do
\t\tlocal kf = Instance.new("Keyframe")
\t\tkf.Name, kf.Time = "KF" .. tostring(k.t), k.t
\t\tlocal root = Instance.new("Pose")
\t\troot.Name, root.CFrame, root.Weight = "HumanoidRootPart", CFrame.new(), 0
\t\tlocal poses = { HumanoidRootPart = root }
\t\tlocal keep = {}
\t\tfor _, pair in ipairs(tree) do
\t\t\tif k.poses[pair[1]] then
\t\t\t\tlocal j = pair[1]
\t\t\t\twhile j and j ~= "HumanoidRootPart" do keep[j] = true j = parentOf[j] end
\t\t\tend
\t\tend
\t\tfor _, pair in ipairs(tree) do
\t\t\tif keep[pair[1]] then
\t\t\t\tlocal p = Instance.new("Pose")
\t\t\t\tp.Name = pair[1]
\t\t\t\tlocal d = k.poses[pair[1]]
\t\t\t\tif d then
\t\t\t\t\tp.CFrame = poseCFrame(d)
\t\t\t\t\tp.Weight = 1
\t\t\t\telse
\t\t\t\t\tp.Weight = 0 -- container only: holds a keyed child, poses nothing itself
\t\t\t\tend
\t\t\t\tp.EasingStyle = Enum.PoseEasingStyle[k.s]
\t\t\t\tp.EasingDirection = Enum.PoseEasingDirection[k.d]
\t\t\t\tp.Parent = poses[pair[2]]
\t\t\t\tposes[pair[1]] = p
\t\t\tend
\t\tend
\t\troot.Parent = kf
\t\tif k.m then
\t\t\tfor _, mname in ipairs(k.m) do
\t\t\t\tlocal mk = Instance.new("KeyframeMarker")
\t\t\t\tmk.Name, mk.Value = mname, ""
\t\t\t\tkf:AddMarker(mk)
\t\t\tend
\t\tend
\t\tkf.Parent = seq
\tend
\treturn seq
end
local parent = ReplicatedStorage
local segs = %(segs)s
for i = 1, #segs - 1 do
\tlocal nxt = parent:FindFirstChild(segs[i])
\tif not nxt then
\t\tnxt = Instance.new("Folder")
\t\tnxt.Name = segs[i]
\t\tnxt.Parent = parent
\tend
\tparent = nxt
end
local old = parent:FindFirstChild(segs[#segs])
while old do old:Destroy() old = parent:FindFirstChild(segs[#segs]) end
local root = Instance.new("Folder")
root.Name = segs[#segs]
local subs = {}
local built = {}
local function add(rig, sub, name, priority, loopAnim, KFS)
\tif not subs[sub] then
\t\tsubs[sub] = Instance.new("Folder")
\t\tsubs[sub].Name = sub
\t\tsubs[sub].Parent = root
\tend
\tlocal s = build(TREES[rig], name, priority, loopAnim, KFS)
\ts.Parent = subs[sub]
\ttable.insert(built, s)
end
'''

TAIL = '''root.Parent = parent
local report = {}
for _, seq in ipairs(built) do
\tlocal nk, len, markers, posed = 0, 0, {}, {}
\tfor _, kf in ipairs(seq:GetChildren()) do
\t\tif kf:IsA("Keyframe") then
\t\t\tnk += 1
\t\t\tif kf.Time > len then len = kf.Time end
\t\t\tfor _, mk in ipairs(kf:GetMarkers()) do table.insert(markers, ("%s@%.3f"):format(mk.Name, kf.Time)) end
\t\t\tfor _, p in ipairs(kf:GetDescendants()) do
\t\t\t\tif p:IsA("Pose") and p.Weight > 0 then posed[p.Name] = true end
\t\t\tend
\t\tend
\tend
\tlocal pl = {}
\tfor k in pairs(posed) do table.insert(pl, k) end
\ttable.sort(pl)
\ttable.insert(report, ("%s/%s: %d kf, %.3fs, %s, loop %s, markers [%s], posed [%s]"):format(
\t\tseq.Parent.Name, seq.Name, nk, len, seq.Priority.Name, tostring(seq.Loop), table.concat(markers, ","), table.concat(pl, ",")))
end
return table.concat(report, "\\n")
'''


def lua_tree(tree):
    return "{" + ",".join('{"%s","%s"}' % (c, p) for c, p in tree) + "}"


def builder(folder, r6_paths, r15_paths, r6_sub="R6", r15_sub="R15"):
    import to_roblox
    segs = folder.split(".")
    if segs[0] == "ReplicatedStorage":
        segs = segs[1:]
    if not segs:
        raise SystemExit("--folder must name a folder under ReplicatedStorage")
    out = [HEAD % {"folder": folder, "r15tree": lua_tree(to_roblox.TREE), "r6tree": lua_tree(R6_TREE),
                   "segs": "{" + ",".join('"%s"' % s for s in segs) + "}"}]
    for p in r15_paths:
        name, pr, lp, kfs = r15_clip_lua(p)
        out.append('add("R15","%s","%s","%s",%s,%s)' % (r15_sub, name, pr, str(lp).lower(), kfs))
    for p in r6_paths:
        name, pr, lp, kfs = r6_clip_lua(json.load(open(p)))
        out.append('add("R6","%s","%s","%s",%s,%s)' % (r6_sub, name, pr, str(lp).lower(), kfs))
    out.append(TAIL)
    return "\n".join(out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--folder", required=True)
    ap.add_argument("--r6", nargs="*", default=[])
    ap.add_argument("--r15", nargs="*", default=[])
    ap.add_argument("--r6-sub", default="R6")
    ap.add_argument("--r15-sub", default="R15")
    a = ap.parse_args()
    sys.stdout.write(builder(a.folder, a.r6, a.r15, a.r6_sub, a.r15_sub))
