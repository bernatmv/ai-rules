#!/usr/bin/env python3
"""Turn Studio KeyframeSequences into REAL uploaded Animation assets, headless.

DEFECT IT EXISTS FOR (2026-10-08): every clip this skill builds is
played through KeyframeSequenceProvider:RegisterKeyframeSequence, whose ids are
session-local. They work in Studio and fail (quietly) in a live server, so the
first time a live playtest with friends was wanted, none of the five
character clips would have played. The only fallback was "right-click,
Save to Roblox" by hand, once per clip.

Open Cloud's Assets API accepts assetType "Animation" as .rbxm (model/x-rbxm).
So, with no hand work:

  1. --emit-dump  writes dump.luau; run it in EDIT mode via execute_luau and save
                  the returned JSON (every KeyframeSequence under --folder)
  2. --build      turns that JSON into one Rojo .model.json per clip and runs
                  `rojo build` -> <Clip>.rbxm (a real Roblox binary, so no
                  hand-written rbxm format)
  3. --upload     uploads each .rbxm as an Animation, POLLS the operation (a 200
                  is acceptance, not completion) and records the asset id
  4. writes apply_ids.luau: run it in edit mode to set an "AnimationId"
     attribute ("rbxassetid://<id>") on each KeyframeSequence; the game's
     controller prefers that attribute over a session registration

    upload_animation.py --emit-dump --folder ReplicatedStorage.MyGame.Animations --out work/anim/upload
    upload_animation.py --dump work/anim/upload/dump.json --out work/anim/upload --build --upload

Environment: ROBLOX_API_KEY (Assets write), ROBLOX_USER_ID or ROBLOX_GROUP_ID.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import time
from pathlib import Path

import requests

HERE = Path(__file__).resolve().parent
ASSETS_URL = "https://apis.roblox.com/assets/v1/assets"
OPERATION_URL = "https://apis.roblox.com/assets/v1/operations/{op}"


def pose_node(p: dict) -> dict:
    c = p["cf"]
    return {
        "name": p["name"],
        "className": "Pose",
        "properties": {
            "CFrame": {"CFrame": {"position": c[0:3],
                                  "orientation": [c[3:6], c[6:9], c[9:12]]}},
            "EasingStyle": {"Enum": int(p["style"])},
            "EasingDirection": {"Enum": int(p["dir"])},
            "Weight": {"Float32": float(p["weight"])},
        },
        "children": [pose_node(k) for k in p.get("children", [])],
    }


def clip_model(clip: dict) -> dict:
    frames = []
    for kf in clip["keyframes"]:
        kids = [pose_node(p) for p in kf["poses"]]
        kids += [{"name": m["name"], "className": "KeyframeMarker",
                  "properties": {"Value": {"String": str(m.get("value", ""))}}}
                 for m in kf.get("markers", [])]
        frames.append({"name": kf.get("name") or "Keyframe", "className": "Keyframe",
                       "properties": {"Time": {"Float32": float(kf["time"])}},
                       "children": kids})
    return {"className": "KeyframeSequence",
            "properties": {"Priority": {"Enum": int(clip["priority"])},
                           "Loop": {"Bool": bool(clip["loop"])}},
            "children": frames}


def build(dump: list, out: Path) -> list[Path]:
    built = []
    for clip in dump:
        name = clip["name"]
        model = out / f"{name}.model.json"
        model.write_text(json.dumps(clip_model(clip), indent=1), encoding="utf-8")
        proj = out / f"{name}.project.json"
        proj.write_text(json.dumps({"name": name, "tree": {"$path": model.name}}), encoding="utf-8")
        rbxm = out / f"{name}.rbxm"
        r = subprocess.run(["rojo", "build", str(proj), "-o", str(rbxm)], capture_output=True, text=True)
        if r.returncode != 0 or not rbxm.exists():
            raise SystemExit(f"rojo build failed for {name}:\n{r.stdout}\n{r.stderr}")
        n_kf = len(clip["keyframes"])
        print(f"[build] {name}: {n_kf} keyframes -> {rbxm.name} ({rbxm.stat().st_size} bytes)")
        built.append(rbxm)
    return built


def upload(path: Path, name: str, creator: dict, key: str, timeout: int) -> str:
    request = {"assetType": "Animation", "displayName": name,
               "description": "Character animation, generated by the roblox-animation skill.",
               "creationContext": {"creator": creator}}
    with path.open("rb") as fh:
        resp = requests.post(ASSETS_URL, headers={"x-api-key": key},
                             files={"request": (None, json.dumps(request), "application/json"),
                                    "fileContent": (path.name, fh, "model/x-rbxm")}, timeout=120)
    if resp.status_code >= 300:
        raise SystemExit(f"upload of {name} refused {resp.status_code}: {resp.text}")
    body = resp.json()
    op = body.get("operationId") or body.get("path", "").rsplit("/", 1)[-1]
    t0 = time.time()
    while time.time() - t0 < timeout:
        r = requests.get(OPERATION_URL.format(op=op), headers={"x-api-key": key}, timeout=60)
        if r.status_code >= 300:
            raise SystemExit(f"poll failed for {name} {r.status_code}: {r.text}")
        b = r.json()
        if b.get("done"):
            aid = (b.get("response") or {}).get("assetId")
            if not aid:
                raise SystemExit(f"{name}: operation done but no assetId: {b}")
            return str(aid)
        time.sleep(2)
    raise SystemExit(f"{name}: operation {op} not done after {timeout}s; re-poll, do not re-upload")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--folder", help="dotted path of the folder holding the KeyframeSequences (searched recursively); REQUIRED with --emit-dump and --upload")
    ap.add_argument("--out", required=True)
    ap.add_argument("--emit-dump", action="store_true")
    ap.add_argument("--dump", help="the JSON dump.luau returned, saved to a file")
    ap.add_argument("--build", action="store_true")
    ap.add_argument("--upload", action="store_true")
    ap.add_argument("--only", help="comma list of clip names")
    ap.add_argument("--timeout", type=int, default=300)
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    if a.emit_dump:
        if not a.folder:
            raise SystemExit("--folder is required with --emit-dump")
        src = (HERE / "luau" / "dump_kfs.luau").read_text(encoding="utf-8")
        (out / "dump.luau").write_text(src.replace("{{FOLDER}}", a.folder), encoding="utf-8")
        print(f"wrote {out / 'dump.luau'}: run it in edit mode, save the returned JSON as dump.json")
        return 0
    if not a.dump:
        raise SystemExit("--dump required (run --emit-dump first)")
    raw = Path(a.dump).read_text(encoding="utf-8").strip()
    if raw.startswith('"'):
        raw = json.loads(raw)  # execute_luau may hand back the string JSON-quoted
    dump = json.loads(raw)
    if a.only:
        keep = {s.strip() for s in a.only.split(",")}
        dump = [c for c in dump if c["name"] in keep]
    if not dump:
        raise SystemExit("no KeyframeSequences in the dump: a verifier must find its own target")
    rbxms = build(dump, out) if a.build else [out / f"{c['name']}.rbxm" for c in dump]
    if not a.upload:
        return 0
    key = os.environ.get("ROBLOX_API_KEY")
    if not key:
        raise SystemExit("ROBLOX_API_KEY not set")
    uid, gid = os.environ.get("ROBLOX_USER_ID"), os.environ.get("ROBLOX_GROUP_ID")
    # checked BEFORE any upload: a refusal after the loop re-uploaded every clip (2026-10-17)
    if not a.folder:
        raise SystemExit("--folder is required: the apply script must point at THIS game's clips")
    creator = {"groupId": str(gid)} if gid else {"userId": str(uid)} if uid else None
    if not creator:
        raise SystemExit("set ROBLOX_USER_ID or ROBLOX_GROUP_ID")
    ids_path = out / "animation_ids.json"
    ids = json.loads(ids_path.read_text(encoding="utf-8")) if ids_path.exists() else {}
    for clip, rbxm in zip(dump, rbxms):
        aid = upload(rbxm, clip["name"], creator, key, a.timeout)
        ids[clip["name"]] = aid
        ids_path.write_text(json.dumps(ids, indent=1), encoding="utf-8")
        print(f"[upload] {clip['name']} -> Animation {aid}")
    # 2026-10-17: the default used to be one game's folder, so an upload run
    # without --folder wrote an apply script that pointed at another game and set nothing; and the
    # lookup was not recursive, so clips in R15/R6 subfolders were never found.
    path_expr = "game." + ".".join(s for s in a.folder.split(".") if s != "game")
    apply = [f"local folder = {path_expr}", "local done = {}"]
    for name, aid in ids.items():
        apply.append(f'do local k = folder:FindFirstChild("{name}", true) if k then '
                     f'k:SetAttribute("AnimationId", "rbxassetid://{aid}") table.insert(done, "{name}") end end')
    apply.append('return "AnimationId set on " .. #done .. ": " .. table.concat(done, ", ")')
    (out / "apply_ids.luau").write_text("\n".join(apply) + "\n", encoding="utf-8")
    print(f"wrote {out / 'apply_ids.luau'}: run it in edit mode, then save the place")
    return 0


if __name__ == "__main__":
    sys.exit(main())
